import assert from 'node:assert/strict';
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:3010';
const headers={'Content-Type':'application/json','x-app-token':process.env.APP_TOKEN};
const post=async()=>{const r=await fetch(base+'/api/stops',{method:'POST',headers,body:'{}'});const j=await r.json();assert.equal(r.status,200,JSON.stringify(j));return j};
const get=async()=>{const r=await fetch(base+'/api/dashboard');assert.equal(r.status,200);return r.json()};
const first=await post();
assert.equal(first.realOrdersEnabled,false);
const exited=first.results.filter(x=>x.status==='PAPER_EXIT');
assert.equal(exited.length,1,JSON.stringify(first));
assert.equal(exited[0].reason,'GAP_THROUGH_STOP');
assert.ok(Math.abs(exited[0].fill-89.91)<0.0001);
const dash=await get();
assert.equal(dash.positions.length,0);
assert.equal(dash.orders.filter(x=>x.side==='SELL').length,2);
assert.ok(Math.abs(dash.cash-489.91)<0.0001);
const second=await post();
assert.equal(second.results.filter(x=>x.status==='PAPER_EXIT').length,0);
const unchanged=await get();
assert.equal(unchanged.orders.length,dash.orders.length);
assert.ok(Math.abs(unchanged.cash-dash.cash)<0.0001);
console.log('PASS gap-through-stop: paper exit only once with adverse slippage, no broker order');
